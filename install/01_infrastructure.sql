-- ============================================================================
-- LetterOne Treasury Platform — Infrastructure
-- Version: 1.0 | Date: 2026-09-29
-- Creates: database, warehouses, compute pool, network rules, stages, roles
-- ============================================================================

USE ROLE ACCOUNTADMIN;

-- Database
CREATE DATABASE IF NOT EXISTS LETTERONE_DB;
USE DATABASE LETTERONE_DB;
USE SCHEMA PUBLIC;

-- Warehouses
CREATE WAREHOUSE IF NOT EXISTS L1_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'General-purpose warehouse for LetterOne platform';

CREATE INTERACTIVE WAREHOUSE IF NOT EXISTS L1_IWH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 86400
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Interactive warehouse for sub-second queries and Cortex Agent';

-- Compute pool for SPCS
CREATE COMPUTE POOL IF NOT EXISTS L1_COMPUTE_POOL
  MIN_NODES = 1
  MAX_NODES = 2
  INSTANCE_FAMILY = CPU_X64_S
  AUTO_SUSPEND_SECS = 3600
  AUTO_RESUME = TRUE
  COMMENT = 'Runs the LetterOne Next.js application';

-- Network rule and External Access Integration
CREATE OR REPLACE NETWORK RULE ALLOW_ALL_RULE
  TYPE = 'HOST_PORT'
  MODE = 'EGRESS'
  VALUE_LIST = ('0.0.0.0:443', '0.0.0.0:80');

CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION ALLOW_ALL_EAI
  ALLOWED_NETWORK_RULES = (ALLOW_ALL_RULE)
  ENABLED = TRUE;

-- Stages
CREATE STAGE IF NOT EXISTS L1_DATA_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Holds CSV/Parquet data files for loading';

CREATE STAGE IF NOT EXISTS L1_DOCUMENT_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Holds PDFs: trustee reports, CLO documents, deal files';

-- ============================================================================
-- Roles and grants
-- ============================================================================

CREATE ROLE IF NOT EXISTS TREASURY_OPS;
CREATE ROLE IF NOT EXISTS RISK;
CREATE ROLE IF NOT EXISTS TRADING_SC;
CREATE ROLE IF NOT EXISTS DIRECT_LENDING;
CREATE ROLE IF NOT EXISTS EXEC_READONLY;

-- All roles inherit from SYSADMIN hierarchy
GRANT ROLE TREASURY_OPS TO ROLE SYSADMIN;
GRANT ROLE RISK TO ROLE SYSADMIN;
GRANT ROLE TRADING_SC TO ROLE SYSADMIN;
GRANT ROLE DIRECT_LENDING TO ROLE SYSADMIN;
GRANT ROLE EXEC_READONLY TO ROLE SYSADMIN;

-- Database-level grants
GRANT USAGE ON DATABASE LETTERONE_DB TO ROLE TREASURY_OPS;
GRANT USAGE ON DATABASE LETTERONE_DB TO ROLE RISK;
GRANT USAGE ON DATABASE LETTERONE_DB TO ROLE TRADING_SC;
GRANT USAGE ON DATABASE LETTERONE_DB TO ROLE DIRECT_LENDING;
GRANT USAGE ON DATABASE LETTERONE_DB TO ROLE EXEC_READONLY;

GRANT USAGE ON SCHEMA LETTERONE_DB.PUBLIC TO ROLE TREASURY_OPS;
GRANT USAGE ON SCHEMA LETTERONE_DB.PUBLIC TO ROLE RISK;
GRANT USAGE ON SCHEMA LETTERONE_DB.PUBLIC TO ROLE TRADING_SC;
GRANT USAGE ON SCHEMA LETTERONE_DB.PUBLIC TO ROLE DIRECT_LENDING;
GRANT USAGE ON SCHEMA LETTERONE_DB.PUBLIC TO ROLE EXEC_READONLY;

-- Warehouse grants
GRANT USAGE ON WAREHOUSE L1_WH TO ROLE TREASURY_OPS;
GRANT USAGE ON WAREHOUSE L1_WH TO ROLE RISK;
GRANT USAGE ON WAREHOUSE L1_WH TO ROLE TRADING_SC;
GRANT USAGE ON WAREHOUSE L1_WH TO ROLE DIRECT_LENDING;
GRANT USAGE ON WAREHOUSE L1_WH TO ROLE EXEC_READONLY;

GRANT USAGE ON WAREHOUSE L1_IWH TO ROLE TREASURY_OPS;
GRANT USAGE ON WAREHOUSE L1_IWH TO ROLE RISK;
GRANT USAGE ON WAREHOUSE L1_IWH TO ROLE TRADING_SC;
GRANT USAGE ON WAREHOUSE L1_IWH TO ROLE DIRECT_LENDING;
GRANT USAGE ON WAREHOUSE L1_IWH TO ROLE EXEC_READONLY;
