GRANT SELECT ON TABLE POSITIONS_IT TO ROLE TREASURY_OPS;
GRANT SELECT ON TABLE POSITIONS_IT TO ROLE RISK;
GRANT SELECT ON TABLE POSITIONS_IT TO ROLE EXEC_READONLY;

GRANT SELECT ON TABLE CASH_IT TO ROLE TREASURY_OPS;
GRANT SELECT ON TABLE CASH_IT TO ROLE RISK;
GRANT SELECT ON TABLE CASH_IT TO ROLE EXEC_READONLY;

GRANT SELECT ON TABLE CLO_PORTFOLIO_IT TO ROLE TRADING_SC;
GRANT SELECT ON TABLE CLO_PORTFOLIO_IT TO ROLE EXEC_READONLY;

GRANT SELECT ON TABLE HEDGE_FUNDS_IT TO ROLE RISK;
GRANT SELECT ON TABLE HEDGE_FUNDS_IT TO ROLE EXEC_READONLY;

GRANT SELECT ON TABLE DEALS_IT TO ROLE DIRECT_LENDING;
