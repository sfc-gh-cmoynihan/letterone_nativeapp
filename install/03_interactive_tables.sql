USE ROLE ACCOUNTADMIN;
USE DATABASE LETTERONE_DB;
USE SCHEMA PUBLIC;
USE WAREHOUSE L1_WH;

-- Positions (latest snapshot only for fast lookup)
CREATE OR REPLACE INTERACTIVE TABLE POSITIONS_IT
  CLUSTER BY (ENTITY)
  DATA_RETENTION_TIME_IN_DAYS = 1
  TARGET_LAG = '1 hour'
  WAREHOUSE = L1_WH
  AS
    SELECT * FROM ENFUSION_POSITIONS
    WHERE SNAPSHOT_DATE = (SELECT MAX(SNAPSHOT_DATE) FROM ENFUSION_POSITIONS);

-- Cash balances (latest snapshot)
CREATE OR REPLACE INTERACTIVE TABLE CASH_IT
  CLUSTER BY (BANK_NAME)
  DATA_RETENTION_TIME_IN_DAYS = 1
  TARGET_LAG = '1 hour'
  WAREHOUSE = L1_WH
  AS
    SELECT * FROM ENFUSION_CASH
    WHERE SNAPSHOT_DATE = (SELECT MAX(SNAPSHOT_DATE) FROM ENFUSION_CASH);

-- CLO portfolio (static-ish, refreshes when marks change)
CREATE OR REPLACE INTERACTIVE TABLE CLO_PORTFOLIO_IT
  CLUSTER BY (MANAGER)
  DATA_RETENTION_TIME_IN_DAYS = 1
  TARGET_LAG = '1 hour'
  WAREHOUSE = L1_WH
  AS
    SELECT * FROM CLO_PORTFOLIO;

-- Hedge fund returns
CREATE OR REPLACE INTERACTIVE TABLE HEDGE_FUNDS_IT
  CLUSTER BY (FUND_NAME)
  DATA_RETENTION_TIME_IN_DAYS = 1
  TARGET_LAG = '1 hour'
  WAREHOUSE = L1_WH
  AS
    SELECT * FROM HEDGE_FUND_RETURNS;

-- Deal library
CREATE OR REPLACE INTERACTIVE TABLE DEALS_IT
  CLUSTER BY (DEAL_STATUS)
  DATA_RETENTION_TIME_IN_DAYS = 1
  TARGET_LAG = '1 hour'
  WAREHOUSE = L1_WH
  AS
    SELECT * FROM DEAL_LIBRARY;

-- Capital accounts (investor reporting)
CREATE OR REPLACE INTERACTIVE TABLE CAPITAL_ACCOUNTS_IT
  CLUSTER BY (INVESTOR_ID)
  DATA_RETENTION_TIME_IN_DAYS = 1
  TARGET_LAG = '1 hour'
  WAREHOUSE = L1_WH
  AS
    SELECT * FROM CAPITAL_ACCOUNTS;

-- Attach all to the interactive warehouse
ALTER INTERACTIVE TABLE POSITIONS_IT SET INTERACTIVE_WAREHOUSE = L1_IWH;
ALTER INTERACTIVE TABLE CASH_IT SET INTERACTIVE_WAREHOUSE = L1_IWH;
ALTER INTERACTIVE TABLE CLO_PORTFOLIO_IT SET INTERACTIVE_WAREHOUSE = L1_IWH;
ALTER INTERACTIVE TABLE HEDGE_FUNDS_IT SET INTERACTIVE_WAREHOUSE = L1_IWH;
ALTER INTERACTIVE TABLE DEALS_IT SET INTERACTIVE_WAREHOUSE = L1_IWH;
ALTER INTERACTIVE TABLE CAPITAL_ACCOUNTS_IT SET INTERACTIVE_WAREHOUSE = L1_IWH;

